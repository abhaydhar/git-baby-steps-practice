def multiply(a, b):
    """Return the product of two numbers."""
    return a * b


def add(a, b):
    """Return the sum of two numbers."""
    return a + b


def subtract(a, b):
    """Return the difference of two numbers."""
    return a - b


def divide(a, b):
    """Return the quotient of two numbers."""
    return a / b 

def divides(a, b):
    """Return the quotients of two numbers."""
    return a / b 